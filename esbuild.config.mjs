import esbuild from 'esbuild';
import path from 'node:path';
import process from 'node:process';
import { builtinModules } from 'node:module';
import { pathToFileURL } from 'node:url';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

/** 生产/开发共用的 esbuild 配置；scripts/check.mjs 复用同一份参数做内存构建比对。 */
export function createBuildOptions(prod) {
	return {
		banner: {
			js: banner,
		},
		entryPoints: ['src/main.ts'],
		bundle: true,
		external: [
			'obsidian',
			'electron',
			'@codemirror/autocomplete',
			'@codemirror/collab',
			'@codemirror/commands',
			'@codemirror/language',
			'@codemirror/lint',
			'@codemirror/search',
			'@codemirror/state',
			'@codemirror/view',
			'@lezer/common',
			'@lezer/highlight',
			'@lezer/lr',
			...builtinModules,
		],
		format: 'cjs',
		target: 'es2021',
		logLevel: 'info',
		sourcemap: prod ? false : 'inline',
		treeShaking: true,
		outfile: 'main.js',
		minify: prod,
	};
}

// 被 scripts/check.mjs import 时只取 createBuildOptions，不启动构建/监听。
const isDirectRun =
	process.argv[1] !== undefined &&
	import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;

if (isDirectRun) {
	const prod = process.argv[2] === 'production';
	const options = createBuildOptions(prod);

	if (prod) {
		await esbuild.build(options);
	} else {
		const context = await esbuild.context(options);
		await context.watch();
	}
}
